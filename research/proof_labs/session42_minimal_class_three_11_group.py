#!/usr/bin/env python3
"""Session42: conditional minimal relative 11-group for an actual T^3 Kummer lift.

A *synthetic* one-dimensional projection of any hypothetical Galois cocycle;
not an actual arithmetic lift or a BSD theorem. See the Session42 note.
"""
from itertools import product, permutations

P = 11
I = (0, (0, 0, 0))


def act(e, x):
    """(1+T)^(-e) x mod (11, T^3), in a scalar coordinate of E[11]."""
    e %= P
    u, v, w = x
    return (u % P, (v-e*u) % P,
            (w-e*v+(e*(e+1)//2)*u) % P)


def mul(a, b):
    e, x = a
    f, y = b
    ay = act(e, y)
    return ((e+f) % P, tuple((x[i]+ay[i]) % P for i in range(3)))


def inv(a):
    e, x = a
    return ((-e) % P, tuple(-v % P for v in act(-e, x)))


def comm(a, b):
    return mul(mul(mul(a, b), inv(a)), inv(b))


def matrix(a):
    e, (u, v, w) = a
    return ((1, 0, 0, u), (-e % P, 1, 0, v),
            (e*(e+1)//2 % P, -e % P, 1, w), (0, 0, 0, 1))


def mm(a, b):
    return tuple(tuple(sum(a[i][k]*b[k][j] for k in range(4)) % P
                       for j in range(4)) for i in range(4))


def determinant3(a):
    # Completely independent permutation determinant formula.
    return ((a[0][0]*(a[1][1]*a[2][2]-a[1][2]*a[2][1])
           - a[0][1]*(a[1][0]*a[2][2]-a[1][2]*a[2][0])
           + a[0][2]*(a[1][0]*a[2][1]-a[1][1]*a[2][0])) % P)


def witnesses(h1=0, h2=0, g1=0, g2=0, g0=1, eh=2, eg=7):
    h = (eh, (0, h1, h2))
    g = (eg, (g0, g1, g2))
    w = mul(mul(g, h), h)  # ell(w) = 7+2*2 = 0 (mod 11).
    c1 = comm(h, w)
    c2 = comm(h, c1)
    c3 = comm(h, c2)
    return h, g, w, c1, c2, c3


def group_size(h, w):
    """Exhaustively enumerate the subgroup generated by h,w and inverses."""
    generators = (h, w, inv(h), inv(w))
    found = {I}
    queue = [I]
    for x in queue:
        for y in generators:
            z = mul(x, y)
            if z not in found:
                found.add(z)
                queue.append(z)
        assert len(found) <= P**4, 'unexpected group order > bound'
    return len(found), sum(x[0] == 0 for x in found)


def arithmetic_inputs():
    """Independent finite counts and minimal-model reduction witnesses."""
    def legendre(z, q):
        z %= q
        return 0 if z == 0 else (1 if pow(z, (q-1)//2, q) == 1 else -1)

    def count(q):
        # Orthogonal finite-field character sum, not the old affine count.
        return q+1+sum(legendre(x*x*x-1267*x+17230, q)
                       for x in range(q))

    assert count(23) == 30 and count(127) == 143
    assert (36-4*23) % P == 10

    def add(u, v, q):
        # Original minimal E: y^2 + xy = x^3 - x^2 - 79x +289.
        if u is None:
            return v
        if v is None:
            return u
        x, y = u
        z, w = v
        if x == z and (y+w+x) % q == 0:
            return None
        slope = ((3*x*x-2*x-79-y)*pow(2*y+x, -1, q)
                 if u == v else (w-y)*pow(z-x, -1, q)) % q
        intercept = (y-slope*x) % q
        xx = (slope*slope+slope+1-x-z) % q
        return xx, (-(slope+1)*xx-intercept) % q

    def times(n, pt, q):
        result = None
        for _ in range(n):
            result = add(result, pt, q)
        return result

    q = 127
    inv4, inv8 = pow(4, -1, q), pow(8, -1, q)
    def minimal(X, Y):
        return (X+1)*inv4 % q, (Y-X-1)*inv8 % q
    p1, p2 = minimal(15, 40), minimal(19, 4)
    twice = add(p1, p1, q)
    x = add(p2, (twice[0], (-twice[1]-twice[0]) % q), q)
    projected = times(13, x, q)
    assert projected is not None and projected == times(26, p1, q)
    assert times(11, projected, q) is None

    def artin(a, b):
        # Calibrated source definition; re-evaluated without old code.
        omega = 16
        num = (a+b*omega) % 121
        den = (a+b*(1-omega)) % 121
        unit = pow(num*pow(den, -1, 121) % 121, 10, 121)
        values = [j for j in range(11) if pow(12, j, 121) == unit]
        assert len(values) == 1
        return values[0]

    assert artin(-5, 2) == 2 and artin(-11, 6) == 4
    assert 12*2 % P == 2 and 10*4 % P == 7


def run():
    arithmetic_inputs()
    assert mul(I, I) == I
    # Arbitrary corrections tested to ensure independence of c1/c2 choices.
    samples = [(0, 0, 0, 0), (5, 1, 4, 9), (10, 10, 10, 10), (2, 3, 7, 8)]
    for h1, h2, g1, g2 in samples:
        h, g, w, c1, c2, c3 = witnesses(h1, h2, g1, g2)
        assert w[0] == 0 and w[1][0] == 1
        assert c1[0] == c2[0] == c3[0] == 0
        assert c1[1][0] == 0 and c1[1][1] == 9
        assert c2 == (0, (0, 0, 4)) and c3 == I
        # Separate affine 4x4 linearization agrees on all generated words.
        assert mm(matrix(h), matrix(g)) == matrix(mul(h, g))
        assert mm(matrix(h), matrix(w)) == matrix(mul(h, w))
        assert mm(matrix(h), mm(matrix(w), matrix(inv(h)))) == matrix(mul(mul(h, w), inv(h)))
        cols = (w[1], c1[1], c2[1])
        rows = tuple(tuple(cols[j][i] for j in range(3)) for i in range(3))
        assert determinant3(rows) == 3  # (-2)^3 = -8 = 3 (mod 11).
        assert group_size(h, w) == (P**4, P**3), 'closure must be 11^4'

    # Check all 11^4 independent choices of first/second scalar corrections.
    # This tests a finite identity; the explanatory note proves it for any V.
    for h1, h2, g1, g2 in product(range(P), repeat=4):
        _, _, w, c1, c2, c3 = witnesses(h1, h2, g1, g2)
        assert w[0] == 0 and w[1][0] == 1
        assert c1[1][1] == 9 and c2 == (0, (0, 0, 4)) and c3 == I
        cols = (w[1], c1[1], c2[1])
        rows = tuple(tuple(cols[j][i] for j in range(3)) for i in range(3))
        assert determinant3(rows) == 3

    # Independent truncation-depth check for r=2..10:
    # delta=(1+T)^-2-1 generates r independent jets; the 11-fold norm vanishes.
    from math import comb

    def pm(a, b, r):
        return tuple(sum(a[i]*b[k-i] for i in range(k+1)) % P
                     for k in range(r))

    for r in range(2, 11):
        a = tuple((-1)**k * comb(k+1, k) % P for k in range(r))
        delta = ((a[0]-1) % P,) + a[1:]
        one = (1,) + (0,)*(r-1)
        power, norm = one, (0,)*r
        for _ in range(P):
            norm = tuple((norm[i]+power[i]) % P for i in range(r))
            power = pm(power, a, r)
        assert power == one and norm == (0,)*r
        vectors = [one]
        for j in range(1, r):
            vectors.append(pm(delta, vectors[-1], r))
        for j, v in enumerate(vectors):
            assert all(x == 0 for x in v[:j])
            assert v[j] == pow(-2, j, P)

    # NEW STRONGER CERTIFICATE: at q23 rho(sigma) has the irreducible
    # polynomial X^2+6X+1, so any u and A*u span V=F11^2. Conjugation by
    # sigma turns three pure-translation jets into SIX independent vectors.
    # Therefore the full relative affine image must be (V[T]/T^3) : C11,
    # of exact order 11^(2*3+1)=11^7, if a global T^3 cocycle exists.
    def vmul(poly, vec):
        out = []
        for k in range(3):
            out.append(tuple(sum(poly[i]*vec[k-i][j] for i in range(k+1)) % P
                             for j in range(2)))
        return tuple(out)

    def a_on(a, vec):
        return tuple(((a[0][0]*xy[0]+a[0][1]*xy[1]) % P,
                      (a[1][0]*xy[0]+a[1][1]*xy[1]) % P) for xy in vec)

    def as_six(vec):
        return tuple(x for xy in vec for x in xy)

    def determinant6(rows):
        # Independent full Leibniz permutation expansion, 720 exact terms.
        out = 0
        for perm in permutations(range(6)):
            invcount = sum(perm[i] > perm[j]
                           for i in range(6) for j in range(i+1, 6))
            term = 1
            for i in range(6):
                term *= rows[i][perm[i]]
            out += (-1 if invcount % 2 else 1)*term
        return out % P

    def rank6(rows):
        # Independent modular Gaussian elimination (not determinant6).
        rows = [list(row) for row in rows]
        rank = 0
        for col in range(6):
            pivot = next((i for i in range(rank, 6) if rows[i][col] % P), None)
            if pivot is None:
                continue
            rows[rank], rows[pivot] = rows[pivot], rows[rank]
            scale = pow(rows[rank][col], -1, P)
            rows[rank] = [(x*scale) % P for x in rows[rank]]
            for i in range(6):
                if i != rank:
                    m = rows[i][col]
                    rows[i] = [(x-m*y) % P for x, y in zip(rows[i], rows[rank])]
            rank += 1
        return rank

    # Companion matrix for q23: X^2+6X+1, whose discriminant 10 is
    # nonsquare in F11. We do NOT identify its basis with a global E[11]
    # torsion basis; its irreducibility property is all that the proof uses.
    A = ((0, 10), (1, 5))
    id2 = ((1, 0), (0, 1))
    def mat2mul(a, b):
        return tuple(tuple(sum(a[i][k]*b[k][j] for k in range(2)) % P
                           for j in range(2)) for i in range(2))
    apow = id2
    for j in range(1, 13):
        apow = mat2mul(apow, A)
        assert (apow == id2) == (j == 12)
    assert ((5*5-4) % P) == 10 and 10 not in {i*i % P for i in range(P)}

    delta3 = (0, 9, 3)  # (1+T)^(-2)-1
    a3 = (1, 9, 3)
    def six_witness(u, v1=(0, 0), v2=(0, 0), rho=A, ch=delta3):
        v = (u, v1, v2)
        columns = []
        for _ in range(3):
            columns.append(as_six(v))
            columns.append(as_six(a_on(rho, vmul(a3, v))))
            v = vmul(ch, v)
        return tuple(tuple(columns[j][i] for j in range(6)) for i in range(6))

    # Independent of the chosen nonzero Kummer vector u and corrections.
    for u in product(range(P), repeat=2):
        if u == (0, 0):
            continue
        rows = six_witness(u, ((u[0]+2) % P, (u[1]+3) % P),
                              ((4*u[0]+1) % P, (7*u[1]+2) % P))
        assert rank6(rows) == 6
    rows0 = six_witness((1, 0))
    assert rank6(rows0) == 6 and determinant6(rows0) == 9
    assert rank6(six_witness((1, 0), rho=id2)) < 6
    assert rank6(six_witness((1, 0), ch=(0, 0, 0))) < 6

    # Critical adversarial controls: without Kummer input, or the 23-prime
    # character, there is no forced class-three 11^4 subgroup.
    h, g, w, c1, c2, _ = witnesses(g0=0)
    assert c2 == I and group_size(h, w) == (11, 1)
    h, g, w, c1, c2, _ = witnesses(eh=0, eg=0)
    assert c2 == I and group_size(h, w) == (11, 11)
    # Wrong sign convention changes the first commutator (but not its square).
    h, g, w, c1, c2, _ = witnesses(eh=-2, eg=-7)
    assert c1[1][1] == 2 and c2[1][2] == 4

    print('PASS: new Legendre point counts, minimal-model Kummer reduction and ray Artin inputs')
    print('PASS: all 14,641 generator correction assignments preserve independent 3-vectors')
    print('PASS: exact 4x4 affine matrix check and exhaustive 11^4 group closure')
    print('PASS: minimal relative p-group has order 11^4=14,641 and class three')
    print('PASS: all 120 nonzero Kummer vectors generate six independent conjugate jets')
    print('PASS: 6x6 determinant, Gaussian rank, and reducible/missing-action controls')
    print('CONDITIONAL: full relative affine image has exact order 11^7=19,487,171')
    print('PASS: zero-Kummer, zero-character and inverse-sign controls')
    print('CONDITIONAL: every actual global T^3 cochain would force this group; existence unproved')
    print("NONCLAIM: no Galois realization, h2, complex L'', Sha or BSD theorem")


if __name__ == '__main__':
    run()
