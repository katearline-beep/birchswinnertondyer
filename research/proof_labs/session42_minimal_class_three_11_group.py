#!/usr/bin/env python3
"""Session42: conditional minimal relative 11-group for an actual T^3 Kummer lift.

A *synthetic* one-dimensional projection of any hypothetical Galois cocycle;
not an actual arithmetic lift or a BSD theorem. See the Session42 note.
"""
from itertools import product

P = 11
I = (0, (0, 0, 0))


def act(e, x):
    """(1+T)^(-e) x mod (11, T^3), in a scalar coordinate of E[11]."""
    e %= P
    u, v, w = x
    return (u % P, (v-e*u) % P,
            (w-e*v+(e*(e+1)//2)*u) % P)


def mul(a, b):
    e, x = a
    f, y = b
    ay = act(e, y)
    return ((e+f) % P, tuple((x[i]+ay[i]) % P for i in range(3)))


def inv(a):
    e, x = a
    return ((-e) % P, tuple(-v % P for v in act(-e, x)))


def comm(a, b):
    return mul(mul(mul(a, b), inv(a)), inv(b))


def matrix(a):
    e, (u, v, w) = a
    return ((1, 0, 0, u), (-e % P, 1, 0, v),
            (e*(e+1)//2 % P, -e % P, 1, w), (0, 0, 0, 1))


def mm(a, b):
    return tuple(tuple(sum(a[i][k]*b[k][j] for k in range(4)) % P
                       for j in range(4)) for i in range(4))


def determinant3(a):
    # Completely independent permutation determinant formula.
    return ((a[0][0]*(a[1][1]*a[2][2]-a[1][2]*a[2][1])
           - a[0][1]*(a[1][0]*a[2][2]-a[1][2]*a[2][0])
           + a[0][2]*(a[1][0]*a[2][1]-a[1][1]*a[2][0])) % P)


def witnesses(h1=0, h2=0, g1=0, g2=0, g0=1, eh=2, eg=7):
    h = (eh, (0, h1, h2))
    g = (eg, (g0, g1, g2))
    w = mul(mul(g, h), h)  # ell(w) = 7+2*2 = 0 (mod 11).
    c1 = comm(h, w)
    c2 = comm(h, c1)
    c3 = comm(h, c2)
    return h, g, w, c1, c2, c3


def group_size(h, w):
    """Exhaustively enumerate the subgroup generated by h,w and inverses."""
    generators = (h, w, inv(h), inv(w))
    found = {I}
    queue = [I]
    for x in queue:
        for y in generators:
            z = mul(x, y)
            if z not in found:
                found.add(z)
                queue.append(z)
        assert len(found) <= P**4, 'unexpected group order > bound'
    return len(found), sum(x[0] == 0 for x in found)


def run():
    assert mul(I, I) == I
    # Arbitrary corrections tested to ensure independence of c1/c2 choices.
    samples = [(0, 0, 0, 0), (5, 1, 4, 9), (10, 10, 10, 10), (2, 3, 7, 8)]
    for h1, h2, g1, g2 in samples:
        h, g, w, c1, c2, c3 = witnesses(h1, h2, g1, g2)
        assert w[0] == 0 and w[1][0] == 1
        assert c1[0] == c2[0] == c3[0] == 0
        assert c1[1][0] == 0 and c1[1][1] == 9
        assert c2 == (0, (0, 0, 4)) and c3 == I
        # Separate affine 4x4 linearization agrees on all generated words.
        assert mm(matrix(h), matrix(g)) == matrix(mul(h, g))
        assert mm(matrix(h), matrix(w)) == matrix(mul(h, w))
        assert mm(matrix(h), mm(matrix(w), matrix(inv(h)))) == matrix(mul(mul(h, w), inv(h)))
        cols = (w[1], c1[1], c2[1])
        rows = tuple(tuple(cols[j][i] for j in range(3)) for i in range(3))
        assert determinant3(rows) == 3  # (-2)^3 = -8 = 3 (mod 11).
        assert group_size(h, w) == (P**4, P**3), 'closure must be 11^4'

    # Check all 11^4 independent choices of first/second scalar corrections.
    # This tests a finite identity; the explanatory note proves it for any V.
    for h1, h2, g1, g2 in product(range(P), repeat=4):
        _, _, w, c1, c2, c3 = witnesses(h1, h2, g1, g2)
        assert w[0] == 0 and w[1][0] == 1
        assert c1[1][1] == 9 and c2 == (0, (0, 0, 4)) and c3 == I
        cols = (w[1], c1[1], c2[1])
        rows = tuple(tuple(cols[j][i] for j in range(3)) for i in range(3))
        assert determinant3(rows) == 3

    # Independent truncation-depth check for r=2..10:
    # delta=(1+T)^-2-1 generates r independent jets; the 11-fold norm vanishes.
    from math import comb

    def pm(a, b, r):
        return tuple(sum(a[i]*b[k-i] for i in range(k+1)) % P
                     for k in range(r))

    for r in range(2, 11):
        a = tuple((-1)**k * comb(k+1, k) % P for k in range(r))
        delta = ((a[0]-1) % P,) + a[1:]
        one = (1,) + (0,)*(r-1)
        power, norm = one, (0,)*r
        for _ in range(P):
            norm = tuple((norm[i]+power[i]) % P for i in range(r))
            power = pm(power, a, r)
        assert power == one and norm == (0,)*r
        vectors = [one]
        for j in range(1, r):
            vectors.append(pm(delta, vectors[-1], r))
        for j, v in enumerate(vectors):
            assert all(x == 0 for x in v[:j])
            assert v[j] == pow(-2, j, P)

    # Critical adversarial controls: without Kummer input, or the 23-prime
    # character, there is no forced class-three 11^4 subgroup.
    h, g, w, c1, c2, _ = witnesses(g0=0)
    assert c2 == I and group_size(h, w) == (11, 1)
    h, g, w, c1, c2, _ = witnesses(eh=0, eg=0)
    assert c2 == I and group_size(h, w) == (11, 11)
    # Wrong sign convention changes the first commutator (but not its square).
    h, g, w, c1, c2, _ = witnesses(eh=-2, eg=-7)
    assert c1[1][1] == 2 and c2[1][2] == 4

    print('PASS: all 14,641 generator correction assignments preserve independent 3-vectors')
    print('PASS: exact 4x4 affine matrix check and exhaustive 11^4 group closure')
    print('PASS: minimal relative p-group has order 11^4=14,641 and class three')
    print('PASS: zero-Kummer, zero-character and inverse-sign controls')
    print('CONDITIONAL: every actual global T^3 cochain would force this group; existence unproved')
    print("NONCLAIM: no Galois realization, h2, complex L'', Sha or BSD theorem")


if __name__ == '__main__':
    run()
