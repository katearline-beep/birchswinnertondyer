from itertools import product
from math import comb

P = 11
Z = (0, 0, 0)
I2 = ((1, 0), (0, 1))
A23 = ((0, 10), (1, 5))  # charpoly X^2+6X+1; order 12
A127 = ((0, 5), (1, 7))  # charpoly X^2+4X+6; order 10


def act(e, x):
    """Scalar multiplication by (1+T)^(-e) in F11[T]/T^3."""
    a, b, c = x
    return a % P, (b-e*a) % P, (c-e*b+(e*(e+1)//2)*a) % P


def add(a, b):
    return tuple((x+y) % P for x, y in zip(a, b))


def neg(a):
    return tuple((-x) % P for x in a)


def mul(s, t):
    e, x = s
    f, y = t
    return ((e+f) % P, add(x, act(e, y)))


def inv(s):
    e, x = s
    return (-e % P, neg(act(-e, x)))


def comm(s, t):
    return mul(mul(mul(s, t), inv(s)), inv(t))


def scalar_double_bracket(h1=0, h2=0, g1=0, g2=0, u=1, eh=2, eg=7):
    h = (eh, (0, h1, h2))
    g = (eg, (u, g1, g2))
    k = comm(h, g)
    t = comm(h, k)
    return k, t


def matmul(A, B):
    return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(2)) % P
                       for j in range(2)) for i in range(2))


def matvec(A, v):
    return tuple(sum(A[i][j]*v[j] for j in range(2)) % P for i in range(2))


def matpower(A, n):
    out = I2
    for _ in range(n):
        out = matmul(out, A)
    return out


def rowspace(A):
    return {tuple((z-y) % P for z, y in zip(matvec(A, v), v))
            for v in product(range(P), repeat=2)}


def vadd(a, b):
    return tuple((x+y) % P for x, y in zip(a, b))


def vscale(n, a):
    return tuple(n*x % P for x in a)


def vpoly_act(e, p):
    a, b, c = p
    return a, vadd(b, vscale(-e, a)), vadd(c, vadd(vscale(-e, b), vscale(e*(e+1)//2, a)))


def affine_mul(s, t):
    A, e, p = s
    B, f, q = t
    q1 = tuple(matvec(A, z) for z in vpoly_act(e, q))
    return matmul(A, B), (e+f) % P, tuple(vadd(x, y) for x, y in zip(p, q1))


def affine_power(s, n):
    out = (I2, 0, ((0, 0), (0, 0), (0, 0)))
    for _ in range(n):
        out = affine_mul(out, s)
    return out


def arithmetic():
    # Point counts via Legendre character sum, independent of affine matrix.
    def count(q):
        return q + 1 + sum(0 if (v := (x*x*x-1267*x+17230) % q) == 0 else
                           (1 if pow(v, (q-1)//2, q) == 1 else -1)
                           for x in range(q))
    assert count(23) == 30 and count(127) == 143
    assert matpower(A23, 12) == I2 and matpower(A127, 10) == I2
    assert all(matpower(A23, j) != I2 for j in range(1, 12))
    assert all(matpower(A127, j) != I2 for j in range(1, 10))
    assert len(rowspace(A23)) == P*P  # all q23 residual local H1_unr is zero
    assert len(rowspace(A127)) == P   # q127 H1_unr is one-dimensional
    u0 = (5, 1)
    assert matvec(A127, u0) == u0 and u0 not in rowspace(A127)

    # The 1-eigencomponent u0 is a LOCAL choice of residual Kummer
    # representative; it is not a shared global torsion coordinate.
    F = (A127, 4, (u0, (0, 0), (0, 0)))
    B, e, (z0, z1, z2) = affine_power(F, 10)
    assert B == I2 and e == 7
    assert (z0, z1, z2) == (vscale(10, u0), vscale(7, u0), vscale(5, u0))
    # Orthogonal exact binomial coefficient sums of Frobenius powers.
    expected = (sum(1 for j in range(10)) % P,
                sum(-4*j for j in range(10)) % P,
                sum(comb(4*j+1, 2) for j in range(10)) % P)
    assert expected == (10, 7, 5)
    assert affine_power((A23, 2, ((0, 0), (0, 0), (0, 0))), 12)[0:2] == (I2, 2)

    # Independent good prime mutator: companion q23 cannot play the q127
    # 1-eigen residual Kummer role, and zero Kummer input kills the tower.
    assert matvec(A23, u0) != u0
    assert affine_power((A127, 4, ((0, 0),)*3), 10)[2] == ((0, 0),)*3
    return expected


def controls():
    # All 11^4 possible first/second correction coordinates on h,g.
    for h1, h2, g1, g2 in product(range(P), repeat=4):
        k, t = scalar_double_bracket(h1, h2, g1, g2)
        assert k[0] == 0 and k[1][0] == 0 and k[1][1] == 9
        assert t == (0, (0, 0, 4)), t
        # The T² quotient satisfies the relator; every lift fails it in
        # T³. Hence the 121-kernel extension has NO group section over
        # the subgroup of the first-order quotient generated by h,g.
    assert scalar_double_bracket(u=0)[1] == (0, Z)
    assert scalar_double_bracket(eh=0)[1] == (0, Z)
    assert scalar_double_bracket(eh=-2, eg=-7)[0][1][1] == 2
    # Multiplying Kummer u by a nonzero scalar changes the double bracket
    # proportionally, not its nonvanishing.
    for u in range(P):
        assert scalar_double_bracket(u=u)[1] == (0, (0, 0, 4*u % P))


